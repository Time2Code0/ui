const sourcePath = "src/registry/marketing/scroll.tsx";

const declaration = /^(export |interface |type |const |function )/;
/** Declarations closer than this are read together as one stop. */
const minStopGap = 8;

async function getSource() {
  // Shiki reads the current time while highlighting, so the output is cached
  // to keep it in the prerendered page.
  "use cache";
  cacheLife("max");

  const file = await fs.readFile(path.join(process.cwd(), sourcePath), "utf-8");
  const code = file.trimEnd();
  const lines = code.split("\n");

  const stops = [0];
  for (const [index, line] of lines.entries()) {
    if (declaration.test(line) && index - (stops.at(-1) ?? 0) >= minStopGap) {
      stops.push(index);
    }
  }

  const highlighted = await highlight(code, {
    components: {
      pre: ({ children }) => <pre>{children}</pre>,
    },
    defaultColor: false,
    lang: "tsx",
    themes: { dark: "github-dark", light: "github-light" },
  });

  return { highlighted, lineCount: lines.length, stops };
}

